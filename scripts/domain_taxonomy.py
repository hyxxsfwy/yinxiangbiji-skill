def canonical_domain(name: str, *, allow_legacy: bool = False) -> str:
    """返回规范领域名；旧名称只能在明确迁移模式下使用。"""
    if name in MANAGED_DOMAINS:
        return name
    if allow_legacy and name in LEGACY_DOMAIN_ALIASES:
        return LEGACY_DOMAIN_ALIASES[name]
    raise ValueError(f"不支持的领域: {name}")


def validate_domain_registry() -> None:
    """校验领域顺序、别名和分类词表契约。"""
    if tuple(DOMAIN_PROFILES) != MANAGED_DOMAINS:
        raise ValueError("领域词表与受管领域顺序不一致")
    if set(LEGACY_DOMAIN_ALIASES.values()) - set(MANAGED_DOMAINS):
        raise ValueError("旧领域别名指向未知领域")
    if set(LEGACY_DOMAIN_ALIASES) & set(MANAGED_DOMAINS):
        raise ValueError("旧领域别名不能同时是受管领域")
    for domain, profile in DOMAIN_PROFILES.items():
        if not profile.get("core") or not profile.get("support"):
            raise ValueError(f"领域词表不完整: {domain}")


validate_domain_registry()
